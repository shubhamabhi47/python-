#Instance Methods:

# Belong to an instance of a class (an object).
# Take self as the first parameter.
# Can access and modify the instance's attributes.
# Called on an object, like obj.method().

#Class methods

# Belong to the class, not a specific instance.
# Take cls as the first parameter.
# Use the @classmethod decorator.
# Can access and modify class-level attributes.
# Called on the class itself, like Class.method().