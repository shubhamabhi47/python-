# using % operator
#Python provides an additional operator %
Integer = 5
Float = 23.4
String = "Abhi"
print(". Hi, I am %s.\n. Int value is %d.\n. Float value is %f.\n"%(String, Integer, Float))
age = 19
name = "Abhi"
txt = f"I am {name}, My age is {age}"
print(txt)

price = 99.27777
final = f"The price is {price : .2f} Dollars"
print (final)

