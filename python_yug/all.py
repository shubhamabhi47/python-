s2  = "Abhimanyu"
# name = f"{s1} {s2}"
# name = " ".join([s1, s2])
# name = s1 + " " + s2
name = s1 + s2
result = ""

for char in name:
    result += char
    if char == "m":
        result += " "   # Add a space after "m"
        break

print(result)
